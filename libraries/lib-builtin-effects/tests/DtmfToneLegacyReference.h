#pragma once

#ifndef MATH_API
#define MATH_API
#endif
#include "SampleCount.h"

#include <algorithm>
#include <cmath>
#include <cstddef>

#ifndef M_PI
#define M_PI 3.14159265358979323846
#endif

namespace DtmfLegacy
{
using wxChar = wchar_t;

#ifndef wxASSERT
#define DTMF_LEGACY_DEFINED_WXASSERT
#define wxASSERT(cond) ((void)0)
#endif

static const double kFadeInOut =
   250.0; // used for fadein/out needed to remove clicking noise

inline bool MakeDtmfTone(
   float* buffer, size_t len, float fs, wxChar tone, sampleCount last,
   sampleCount total, float amplitude)
{
   /*
     --------------------------------------------
                 1209 Hz 1336 Hz 1477 Hz 1633 Hz

                             ABC     DEF
      697 Hz          1       2       3       A

                     GHI     JKL     MNO
      770 Hz          4       5       6       B

                     PQRS     TUV     WXYZ
      852 Hz          7       8       9       C

                             oper
      941 Hz          *       0       #       D
     --------------------------------------------
     Essentially we need to generate two sin with
     frequencies according to this table, and sum
     them up.
     sin wave is generated by:
      s(n)=sin(2*pi*n*f/fs)

     We will precalculate:
        A= 2*pi*f1/fs
        B= 2*pi*f2/fs

     And use two switch statements to select the frequency

     Note: added support for letters, like those on the keypad
           This support is only for lowercase letters: uppercase
           are still considered to be the 'military'/carrier extra
           tones.
   */

   float f1, f2 = 0.0;
   double A, B;

   // select low tone: left column
   switch (tone)
   {
   case '1':
   case '2':
   case '3':
   case 'A':
   case 'a':
   case 'b':
   case 'c':
   case 'd':
   case 'e':
   case 'f':
      f1 = 697;
      break;
   case '4':
   case '5':
   case '6':
   case 'B':
   case 'g':
   case 'h':
   case 'i':
   case 'j':
   case 'k':
   case 'l':
   case 'm':
   case 'n':
   case 'o':
      f1 = 770;
      break;
   case '7':
   case '8':
   case '9':
   case 'C':
   case 'p':
   case 'q':
   case 'r':
   case 's':
   case 't':
   case 'u':
   case 'v':
   case 'w':
   case 'x':
   case 'y':
   case 'z':
      f1 = 852;
      break;
   case '*':
   case '0':
   case '#':
   case 'D':
      f1 = 941;
      break;
   default:
      f1 = 0;
   }

   // select high tone: top row
   switch (tone)
   {
   case '1':
   case '4':
   case '7':
   case '*':
   case 'g':
   case 'h':
   case 'i':
   case 'p':
   case 'q':
   case 'r':
   case 's':
      f2 = 1209;
      break;
   case '2':
   case '5':
   case '8':
   case '0':
   case 'a':
   case 'b':
   case 'c':
   case 'j':
   case 'k':
   case 'l':
   case 't':
   case 'u':
   case 'v':
      f2 = 1336;
      break;
   case '3':
   case '6':
   case '9':
   case '#':
   case 'd':
   case 'e':
   case 'f':
   case 'm':
   case 'n':
   case 'o':
   case 'w':
   case 'x':
   case 'y':
   case 'z':
      f2 = 1477;
      break;
   case 'A':
   case 'B':
   case 'C':
   case 'D':
      f2 = 1633;
      break;
   default:
      f2 = 0;
   }

   // precalculations
   A = B = 2 * M_PI / fs;
   A *= f1;
   B *= f2;

   // now generate the wave: 'last' is used to avoid phase errors
   // when inside the inner for loop of the Process() function.
   for (decltype(len) i = 0; i < len; i++)
   {
      buffer[i] =
         amplitude * 0.5 *
         (sin(A * (i + last).as_double()) + sin(B * (i + last).as_double()));
   }

   // generate a fade-in of duration 1/250th of second
   if (last == 0)
   {
      A = std::min<double>(len, (fs / kFadeInOut));
      for (size_t i = 0; i < A; i++)
      {
         buffer[i] *= i / A;
      }
   }

   // generate a fade-out of duration 1/250th of second
   if (last >= total - len)
   {
      // we are at the last buffer of 'len' size, so, offset is to
      // backup 'A' samples, from 'len'
      A = std::min<double>(len, (fs / kFadeInOut));
      size_t offset = len - A;
      wxASSERT(offset >= 0);
      for (size_t i = 0; i < A; i++)
      {
         buffer[i + offset] *= (1 - (i / A));
      }
   }
   return true;
}

#ifdef DTMF_LEGACY_DEFINED_WXASSERT
#undef wxASSERT
#undef DTMF_LEGACY_DEFINED_WXASSERT
#endif
} // namespace DtmfLegacy
